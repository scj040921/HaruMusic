import assert from 'node:assert/strict';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createServer } from 'node:http';
import { resolve } from 'node:path';
const { _electron } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const profile=resolve('artifacts/desktop-ui-profile-0.1.14');mkdirSync(profile,{recursive:true});
const occupied=createServer((_,res)=>{res.writeHead(503);res.end('test fixture');});
await new Promise(resolve=>occupied.listen(0,'127.0.0.1',resolve));
const occupiedPort=occupied.address().port;
const settings=JSON.parse(readFileSync('src/main/set.json','utf8'));
writeFileSync(resolve(profile,'config.json'),JSON.stringify({set:{...settings,musicApiPort:occupiedPort}}));
let app;
try {
 app=await _electron.launch({executablePath:resolve('node_modules/electron/dist/electron.exe'),args:['--user-data-dir='+profile,'out/main/index.js'],timeout:30000});
 assert.equal(await app.evaluate(({app})=>app.getPath('userData')),profile,'desktop fixture must use an isolated profile');
 const page=await app.firstWindow();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.waitForLoadState('domcontentloaded');
 const activePort=await page.evaluate(()=>window.electron.ipcRenderer.sendSync('get-store-value','set').musicApiPort);
 assert.notEqual(activePort,occupiedPort,'desktop startup must move past an occupied real port');
 const ready=await fetch('http://127.0.0.1:'+activePort+'/__fixture_not_found',{signal:AbortSignal.timeout(3000)});
 assert.equal(ready.status,404,'API must already be listening when the renderer is available');
 await page.evaluate(()=>{localStorage.setItem('haru-salt-mode','true');localStorage.setItem('haru-liquid-mode','false');localStorage.setItem('music-full-config',JSON.stringify({fontSize:28,saltPlayerTheme:'dark'}));});
 await page.reload();
 const agree=page.getByText('我已阅读并同意',{exact:true});if(await agree.isVisible())await agree.click();
 await page.waitForSelector('.liquid-sidebar');
 assert.equal(await page.getByText('切换 Salt UI',{exact:true}).count(),0);
 assert.deepEqual(await page.evaluate(()=>({old:localStorage.getItem('haru-salt-mode'),liquid:localStorage.getItem('haru-liquid-mode')})),{old:null,liquid:'true'});
 await page.evaluate(()=>{
  const pinia=document.getElementById('app').__vue_app__.config.globalProperties.$pinia;
  const core=pinia._s.get('playerCore');
  const svg='<svg xmlns="http://www.w3.org/2000/svg" width="600" height="600"><rect width="600" height="600" fill="#185b64"/><circle cx="400" cy="270" r="180" fill="#ddbc8c"/><path d="M0 360L600 90V600H0" fill="#333b4c"/></svg>';
  core.playMusic={id:'desktop-fixture',source:'local',name:'Liquid / 光的形状',ar:[{id:1,name:'HaruMusic'}],picUrl:'data:image/svg+xml,'+encodeURIComponent(svg),primaryColor:'#346a72'};
 });
 await page.waitForSelector('.music-play-bar');await page.waitForTimeout(300);
 await page.locator('.music-content-title').first().click();
 await page.waitForSelector('.liquid-now-playing');await page.waitForTimeout(600);
 assert.equal(await page.locator('[class*="salt-"]').count(),0);
 const config=await page.evaluate(()=>JSON.parse(localStorage.getItem('music-full-config')));
 assert.equal(config.fontSize,28);assert.equal(Object.keys(config).some(k=>k.startsWith('salt')),false);
 mkdirSync('artifacts/ui-0.1.14',{recursive:true});await page.screenshot({path:'artifacts/ui-0.1.14/desktop-liquid.png'});
 await page.evaluate(()=>{const pinia=document.getElementById('app').__vue_app__.config.globalProperties.$pinia;const queue=pinia._s.get('playlist'),core=pinia._s.get('playerCore');queue.setPlayList([core.playMusic,...Array.from({length:14},(_,i)=>({id:i+10,source:'netease',name:'Desktop selection '+i,ar:[{name:'Collection'}],picUrl:'',al:{name:'Album'}}))]);queue.setPlayListDrawerVisible(true);});
 const queue=page.getByRole('dialog',{name:'播放队列',exact:true});await queue.waitFor();
 await page.getByRole('searchbox',{name:'搜索播放队列'}).fill('selection 7');assert.equal(await queue.locator('.queue-row').count(),1);
 assert.ok(await queue.evaluate(e=>e.contains(document.activeElement)));
 await page.waitForFunction(()=>{const e=document.querySelector('.playlist-panel');return e&&getComputedStyle(e).opacity==='1'&&![...e.classList].some(c=>c.includes('enter-active'));});
 const material=await queue.evaluate(e=>({opacity:getComputedStyle(e).opacity,background:getComputedStyle(e).backgroundColor,blur:getComputedStyle(e).backdropFilter}));
 assert.equal(material.opacity,'1');assert.equal(material.background,'rgb(255, 255, 255)');assert.equal(material.blur,'none');
 await page.screenshot({path:'artifacts/ui-0.1.14/desktop-queue.png'});
 await page.getByRole('button',{name:'关闭播放队列',exact:true}).click();await queue.waitFor({state:'detached'});assert.ok(await page.locator('.liquid-now-playing').isVisible());
 assert.deepEqual(errors,[]);console.log('Actual Electron renderer: Salt migration persisted, obsolete settings removed, Liquid player and cover rendered.');
} finally {await app?.close();await new Promise(resolve=>occupied.close(resolve));}
